#!/usr/bin/env python
"""Numeric report (markdown tables with 95% CIs and paired differences) -> results/REPORT.md"""
import csv, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
sys.path.insert(0, os.path.dirname(__file__))
import numpy as np
from edr.evaluate import ci95
from make_figures import read, sel

ROOT = os.path.join(os.path.dirname(__file__), "..", "results")
out = ["# Results (auto-generated by scripts/make_report.py)\n",
       "All numbers: 100 held-out test instances (seeds 2,000,000,000+), U15G5, **one training seed**; "
       "± is the 95% CI of the mean (t-distribution) over instances. Paired differences use the same instances/events.\n"]


def pd(a, b, key):
    d = np.array([x[key] - y[key] for x, y in zip(a, b)], float)
    return f"{d.mean():+.1f} ± {ci95(d):.1f}"


def line(name, rr, extra=""):
    T = np.array([r["T"] for r in rr]); E = np.array([r["E"] for r in rr])
    return (f"| {name} | {T.mean():.1f} ± {ci95(T):.1f} | {E.mean():.0f} ± {ci95(E):.0f} | "
            f"{100*np.mean([r['over'] for r in rr]):.0f}% | {100*np.mean([r['failed'] for r in rr]):.1f}% | "
            f"{np.mean([r['replans'] for r in rr]):.2f} |{extra}")


hdr = "| policy | T (min) | E (kJ) | over budget | failures | replans |"
for tag in ("U15G5_2U1G", "U15G5_2U2G"):
    d = os.path.join(ROOT, tag)
    out.append(f"\n## {tag}\n")
    pa = os.path.join(d, "stageA.csv")
    if os.path.exists(pa):
        A = read(pa)
        out.append("### Stage A - static roads, energy budget B = beta*B0 (RQ1, RQ2)\n")
        for beta in (0.7, 0.8, 0.9, 1.0):
            out.append(f"\n**beta = {beta}**\n\n{hdr} T vs P0+ control (paired) | E vs P0+ control (paired) |\n|---|---|---|---|---|---|---|---|")
            ctrl = sel(A, policy="P0+ (control)", beta=beta)
            for pol in dict.fromkeys(r["policy"] for r in A):
                rr = sel(A, policy=pol, beta=beta)
                if not rr:
                    continue
                extra = f" {pd(rr, ctrl, 'T')} | {pd(rr, ctrl, 'E')} |" if ctrl and pol != "P0+ (control)" else " - | - |"
                out.append(line(pol, rr, extra))
    pb = os.path.join(d, "stageB.csv")
    if os.path.exists(pb):
        B = read(pb)
        ev = [r for r in B if r["kind"] != "none"]
        out.append(f"\n### Stage B - blocked / slow roads (18 events x 100 instances), budget B = 0.9*B0 (RQ3, RQ4)\n\n{hdr}\n|---|---|---|---|---|---|")
        for pol in dict.fromkeys(r["policy"] for r in B):
            out.append(line(pol, [r for r in ev if r["policy"] == pol]))
        base = "P0 open-loop (base)"
        st = {r["seed"]: r for r in sel(B, policy=base, kind="none")}
        out.append("\n**Effect of the event on the base policy, open loop (RQ3 / H3)** - mean increase vs the same instance on static roads\n\n"
                   "| event | level | dT % | dE % |\n|---|---|---|---|")
        for kind in ("block", "slow"):
            for lv in ("low", "medium", "high"):
                rr = sel(B, policy=base, kind=kind, level=lv)
                dT = [100 * (r["T"] / st[r["seed"]]["T"] - 1) for r in rr]; dE = [100 * (r["E"] / st[r["seed"]]["E"] - 1) for r in rr]
                out.append(f"| {kind} | {lv} | {np.mean(dT):+.1f} ± {ci95(dT):.1f} | {np.mean(dE):+.1f} ± {ci95(dE):.1f} |")
        out.append("\n| timing | dT % | dE % |\n|---|---|---|")
        for tm in ("early", "middle", "late"):
            rr = sel(B, policy=base, timing=tm)
            dT = [100 * (r["T"] / st[r["seed"]]["T"] - 1) for r in rr]; dE = [100 * (r["E"] / st[r["seed"]]["E"] - 1) for r in rr]
            out.append(f"| {tm} | {np.mean(dT):+.1f} ± {ci95(dT):.1f} | {np.mean(dE):+.1f} ± {ci95(dE):.1f} |")
        out.append("\n**Paired: event-triggered minus periodic (same policy, same events)**\n\n| policy | dT (min) | dE (kJ) | d replans |\n|---|---|---|---|")
        for a, b in [("P0 event + road layer", "P0 periodic + road layer"), ("P4 event + road layer", "P4 periodic + road layer")]:
            ra = [r for r in ev if r["policy"] == a]; rb = [r for r in ev if r["policy"] == b]
            if ra and rb:
                out.append(f"| {a.split(' event')[0]} | {pd(ra, rb, 'T')} | {pd(ra, rb, 'E')} | {pd(ra, rb, 'replans')} |")
        out.append("\n**Paired: road layer + event-triggered replanning minus open loop (same policy)**\n\n| policy | dT (min) | dE (kJ) |\n|---|---|---|")
        for a, b in [("P0 event + road layer", "P0 open-loop (base)"), ("P0+ (control) event + road layer", "P0+ (control) open-loop"),
                     ("P4 event + road layer", "P4 open-loop")]:
            ra = [r for r in ev if r["policy"] == a]; rb = [r for r in ev if r["policy"] == b]
            if ra and rb:
                out.append(f"| {a.split(' event')[0]} | {pd(ra, rb, 'T')} | {pd(ra, rb, 'E')} |")
        out.append("\n**Paired: candidate methods vs the P0+ control, both with road layer + event-triggered replanning**\n\n| policy | dT (min) | dE (kJ) | over-budget rate |\n|---|---|---|---|")
        ctrl = [r for r in ev if r["policy"] == "P0+ (control) event + road layer"]
        for pol in ("P4 event + road layer", "P3 (beta=0.9) event + road layer", "P4 (road-event trained) event", "P0 (road-event trained) event", "P1 route filter, event"):
            rr = [r for r in ev if r["policy"] == pol]
            if rr and ctrl:
                out.append(f"| {pol} | {pd(rr, ctrl, 'T')} | {pd(rr, ctrl, 'E')} | {100*np.mean([r['over'] for r in rr]):.0f}% vs {100*np.mean([r['over'] for r in ctrl]):.0f}% |")
        out.append("\n**Euclidean vs road-distance UAV->UGV assignment (event-triggered)** "
                   + ("- with one UGV the assignment is trivial, so the two are identical by construction.\n" if tag.endswith("2U1G") else "\n"))
        out.append("\n| policy | road-distance minus Euclid: dT (min) | dE (kJ) |\n|---|---|---|")
        for nm, a_, b_ in [("P0", "P0 event + road layer", "P0 event, road-distance assignment"),
                           ("P0+", "P0+ (control) event + road layer", "P0+ event, road-distance assignment"),
                           ("P4", "P4 event + road layer", "P4 event, road-distance assignment")]:
            ra = [r for r in ev if r["policy"] == a_]; rb = [r for r in ev if r["policy"] == b_]
            if ra and rb:
                out.append(f"| {nm} | {pd(rb, ra, 'T')} | {pd(rb, ra, 'E')} |")
    ps = os.path.join(d, "stageS.csv")
    if os.path.exists(ps):
        S = read(ps)
        out.append("\n### Stress test - one bridge blocked (map disconnected), failures per policy\n\n| policy | failure rate | n |\n|---|---|---|")
        for pol in dict.fromkeys(r["policy"] for r in S):
            rr = [r for r in S if r["policy"] == pol]
            out.append(f"| {pol} | {100*np.mean([r['failed'] for r in rr]):.0f}% | {len(rr)} |")
open(os.path.join(ROOT, "REPORT.md"), "w").write("\n".join(out) + "\n")
print("wrote results/REPORT.md")
